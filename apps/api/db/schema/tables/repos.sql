CREATE TABLE repos (
    full_name text,
    url text NOT NULL,
    description text,
    stars integer DEFAULT 0 NOT NULL,
    owner text NOT NULL,
    owner_avatar text,
    owner_location text,
    country text,
    default_branch text,
    homepage text,
    created_at timestamptz,
    pushed_at timestamptz,
    discovered_via text[] DEFAULT '{}' NOT NULL,
    dependencies jsonb DEFAULT '{}' NOT NULL,
    window_commits integer,
    total_commits integer,
    scanned_at timestamptz,
    topics text[] DEFAULT '{}' NOT NULL,
    stellar_added_in_window boolean,
    language text,
    license text,
    forks integer DEFAULT 0 NOT NULL,
    base_sha text,
    declared_track text,
    hackathon text DEFAULT 'hackmeridian-2026' NOT NULL,
    CONSTRAINT repos_pkey PRIMARY KEY (full_name)
);
